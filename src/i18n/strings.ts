export const STRINGS: Record<Lang, Record<StringKey, string>> = { fr, en };

/** Amounts are stored in millions: 500 → "500M", 1200 → "1,2 Md" / "1.2B". */
export function formatMoney(millions: number, lang: Lang): string {
  if (millions >= 1000) {
    const value = (millions / 1000).toLocaleString(lang === 'fr' ? 'fr-FR' : 'en-US', {
      maximumFractionDigits: 2,
    });
    return lang === 'fr' ? `${value} Md` : `${value}B`;
  }
  return `${millions}M`;
}
