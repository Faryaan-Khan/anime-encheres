// Bundles the "opponent" Edge Function into one file that can be pasted into
// the Supabase dashboard editor (or deployed with the Supabase CLI).
import { build } from 'esbuild';

await build({
  entryPoints: [new URL('../supabase/functions/opponent/index.ts', import.meta.url).pathname],
  outfile: new URL('../supabase/functions/opponent/bundle.js', import.meta.url).pathname,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  // Card pictures are a browser-only feature (Vite's import.meta.glob).
  define: { 'import.meta.glob': 'globalThis.__noGlob' },
  banner: { js: 'globalThis.__noGlob = () => ({});\n// Generated by `npm run build:opponent` from supabase/functions/opponent/index.ts. Do not edit.' },
  legalComments: 'none',
});
console.log('Wrote supabase/functions/opponent/bundle.js');
